package org.jackhuang.hmcl.ql;

import org.jetbrains.annotations.NotNullByDefault;

import java.time.format.DateTimeFormatter;

/// Fixed settings of the Qinglan fork that are baked into the launcher build.
@NotNullByDefault
public final class QLConstants {

    /// The wall-clock formatter ({@code HH:mm:ss}) shared by the QL pages that
    /// stamp refresh or arrival times into status labels.
    public static final DateTimeFormatter WALL_CLOCK = DateTimeFormatter.ofPattern("HH:mm:ss");

    /// Update source baked into this build; deliberately empty.
    ///
    /// <p>There is no public manifest URL yet: the previous placeholder
    /// (a placeholder host that never existed). The real source travels with the pack and
    /// is recorded in the instance's {@code ql-manifest-state.json} by the seed import, so
    /// an instance without one simply has nothing to update from and says so.</p>
    public static final String DEFAULT_MANIFEST_URL = "";

    /// File name suffix marking a managed file parked by a disabled optional-mod group.
    ///
    /// <p>Shared by the sync engine, the seed importer and the dblpack exporter; changing
    /// the value must go through every consumer of disabled files.</p>
    public static final String DISABLED_SUFFIX = ".disabled";

    /// File name of the per-instance dblpack inventory generated by the seed importer.
    public static final String DBLPACK_FILE = "dblpack.json";

    private QLConstants() {
    }
}
